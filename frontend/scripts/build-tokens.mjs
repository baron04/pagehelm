/**
 * Compile the design tokens and the server's contract facts into build-time sources.
 *
 * The palette and scale are the frontend's (`src/styles/design_tokens.json`); the panel and
 * the trace replay page (`build-trace.mjs`) are both generated from them. Generating the
 * stylesheet keeps the values in one file and keeps the contrast gate meaningful.
 *
 * The panel protocol version is generated for the same reason the palette is: the Runtime
 * and the panel each check the server's `protocol` against their own build, and until now
 * they stated it separately -- one from the contract JSON, one as a hand-written `1`.
 *
 * The standing entry needs the palette too, and cannot inherit it: it renders before any
 * panel exists, in its own shadow root where none of these custom properties are declared.
 * So its colours are generated as literals -- the same numbers, checked once, from the
 * same file. What used to be a hand-copied approximation is how `#2557dd` grew alongside
 * the accent it was meant to be.
 */
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs'
import {dirname, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'
import {customProperties as block, readTokens} from './tokens.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const target = resolve(here, '../src/styles/_tokens.generated.scss')
const tokens = readTokens()

const contractSource = resolve(here, '../../src/web_operation_agent/web_runtime/panel_contract.json')
const protocolTarget = resolve(here, '../src/contract/protocol.generated.ts')
const {protocol} = JSON.parse(readFileSync(contractSource, 'utf8'))

const entryTarget = resolve(here, '../src/runtime/entry-palette.generated.ts')

// The panel lives in a shadow root, where `:root` matches nothing: custom properties have
// to be declared on `:host`. The document's theme choice is mirrored onto the host element
// by `mount.tsx`, because `:host-context()` is not portable.
const css = `// Generated by scripts/build-tokens.mjs from
// frontend/src/styles/design_tokens.json. Do not edit by hand.
:host {
${block(tokens.scale)}
${block(tokens.themes.light)}
  color-scheme: light;
}

:host([data-theme='dark']) {
${block(tokens.themes.dark)}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :host(:not([data-theme='light'])) {
${block(tokens.themes.dark).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
`
mkdirSync(dirname(target), {recursive: true})
writeFileSync(target, css)
// A literal, not an import of the contract JSON: the Runtime bundle stays free of the 63
// labels it does not render just to check one integer.
mkdirSync(dirname(protocolTarget), {recursive: true})
writeFileSync(protocolTarget, `// Generated by scripts/build-tokens.mjs from
// src/web_operation_agent/web_runtime/panel_contract.json. Do not edit by hand.
export const PANEL_PROTOCOL: number = ${protocol}
`)

// The entry picks exactly the roles its own markup uses; an invented role would be a
// second opinion about what the palette means, so `entry.ts` names these keys back.
const entryPalette = t => ({
  ink: t.ink, muted: t['ink-muted'], card: t['surface-raised'], line: t.line,
  lineStrong: t['line-strong'], accent: t.accent, button: t['surface-muted'],
  warning: t.warning, shadow: t['shadow-2'],
})
const entryBlock = (name, values) =>
  `export const ${name} = {\n` +
  Object.entries(values).map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`).join('\n') +
  `\n}`
mkdirSync(dirname(entryTarget), {recursive: true})
writeFileSync(entryTarget, `// Generated by scripts/build-tokens.mjs from
// frontend/src/styles/design_tokens.json. Do not edit by hand.
${entryBlock('ENTRY_LIGHT', entryPalette(tokens.themes.light))}

${entryBlock('ENTRY_DARK', entryPalette(tokens.themes.dark))}
`)
process.stdout.write(
  `tokens -> ${target}\nprotocol -> ${protocolTarget}\nentry palette -> ${entryTarget}\n`)
